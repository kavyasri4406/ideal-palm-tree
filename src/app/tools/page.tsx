const getSymptomsForCrop = (cropId: string): Symptom[] => {
  const base = getBaseSymptomsForCrop(cropId);
  const crop = CROPS.find(c => c.id === cropId) || CROPS[0];
  const names: CropNames = { kn: cropName(crop, "kn"), ml: cropName(crop, "ml"), hi: cropName(crop, "hi") };
  const extras = PEST_EXTRA[cropId]
    || (crop.category === "Fruits"
      ? PEST_EXTRA_FALLBACK.fruit(names)
      : crop.category === "Vegetables" || crop.category === "Spices"
        ? PEST_EXTRA_FALLBACK.veg(names)
        : PEST_EXTRA_FALLBACK.default(names));
  const toAdvice = (r: PestRow): DiseaseAdvice => ({ name: r[1], organic: r[2], chemical: r[3] });
  return base.map((s, i) => {
    const x = extras[i];
    if (!x) return s;
    return {
      ...s,
      labelKN: x.kn[0], labelML: x.ml[0], labelHI: x.hi[0],
      diseases: { ...s.diseases, kn: toAdvice(x.kn), ml: toAdvice(x.ml), hi: toAdvice(x.hi) }
    };
  });
};

